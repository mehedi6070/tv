function render(list){

    channelBox.innerHTML = "";

    count.innerText =
        list.length + " Channels";


    if(list.length === 0){

        channelBox.innerHTML =
            '<div class="channel">No channel found</div>';

        return;

    }


    list.forEach(function(channel){

        const realIndex =
            channels.indexOf(channel);


        const div =
            document.createElement("div");


        div.className =
            "channel";


        if(realIndex === activeIndex){

            div.classList.add("active");

        }


        div.innerHTML = `

            <div class="channelName">
                ${escapeHTML(channel.name)}
            </div>

            <div class="channelLive">
                ● LIVE
            </div>

            <div class="star">
                ☆
            </div>

        `;


        div.onclick = function(){

            play(realIndex);

        };


        const star =
            div.querySelector(".star");


        star.onclick = function(event){

            event.stopPropagation();

            toggleFavorite(
                realIndex,
                star
            );

        };


        updateStar(
            realIndex,
            star
        );


        channelBox.appendChild(div);

    });

}


/* ========================================
   PLAY CHANNEL
======================================== */

function play(index){

    const channel =
        channels[index];


    if(!channel)
        return;


    activeIndex =
        index;


    current.innerText =
        channel.name;


    status.innerText =
        "LOADING...";


    if(hls){

        hls.destroy();

        hls = null;

    }


    video.pause();

    video.removeAttribute("src");

    video.load();


    const streamURL =
        channel.url;


    /* ====================================
       NATIVE HLS
    ==================================== */

    if(
        video.canPlayType(
            "application/vnd.apple.mpegurl"
        )
    ){

        video.src =
            streamURL;


        video.addEventListener(
            "loadedmetadata",
            function nativePlay(){

                video.removeEventListener(
                    "loadedmetadata",
                    nativePlay
                );


                status.innerText =
                    "● LIVE";


                video.play()
                    .catch(function(){

                        status.innerText =
                            "PRESS PLAY";

                    });

            }
        );


        video.addEventListener(
            "error",
            function(){

                status.innerText =
                    "STREAM ERROR";

            },
            {once:true}
        );

    }


    /* ====================================
       HLS.JS
    ==================================== */

    else if(
        typeof Hls !== "undefined" &&
        Hls.isSupported()
    ){

        hls =
            new Hls({

                enableWorker:true,

                lowLatencyMode:false,

                backBufferLength:30,

                maxBufferLength:30,

                maxMaxBufferLength:60,

                liveSyncDurationCount:3,

                liveMaxLatencyDurationCount:6,

                fragLoadingMaxRetry:4,

                manifestLoadingMaxRetry:4,

                levelLoadingMaxRetry:4

            });


        hls.loadSource(
            streamURL
        );


        hls.attachMedia(
            video
        );


        hls.on(
            Hls.Events.MANIFEST_PARSED,
            function(){

                status.innerText =
                    "● LIVE";


                video.play()
                    .catch(function(){

                        status.innerText =
                            "PRESS PLAY";

                    });

            }
        );


        hls.on(
            Hls.Events.ERROR,
            function(event,data){

                console.log(
                    "HLS ERROR:",
                    data
                );


                if(data.fatal){

                    status.innerText =
                        "STREAM ERROR";


                    if(
                        data.type ===
                        Hls.ErrorTypes.NETWORK_ERROR
                    ){

                        status.innerText =
                            "RECONNECTING...";


                        setTimeout(
                            function(){

                                if(hls){

                                    hls.startLoad();

                                }

                            },
                            2000
                        );

                    }


                    else if(
                        data.type ===
                        Hls.ErrorTypes.MEDIA_ERROR
                    ){

                        status.innerText =
                            "RECOVERING...";


                        if(hls){

                            hls.recoverMediaError();

                        }

                    }

                }

            }
        );

    }


    else{

        status.innerText =
            "HLS NOT SUPPORTED";

    }


    render(
        getFiltered()
    );

}


