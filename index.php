    }


    let newIndex =
        activeIndex - 1;


    if(newIndex < 0){

        newIndex =
            channels.length - 1;

    }


    play(newIndex);

}


/* ========================================
   NEXT
======================================== */

function nextChannel(){

    if(channels.length === 0)
        return;


    if(activeIndex === -1){

        play(0);

        return;

    }


    let newIndex =
        activeIndex + 1;


    if(
        newIndex >= channels.length
    ){

        newIndex = 0;

    }


    play(newIndex);

}


/* ========================================
   SEARCH
======================================== */

function getFiltered(){

    const text =
        search.value
        .trim()
        .toLowerCase();


    if(!text){

        return channels;

    }


    return channels.filter(
        function(channel){

            return channel.name
                .toLowerCase()
                .includes(text);

        }
    );

}


search.addEventListener(
    "input",
    function(){

        render(
            getFiltered()
        );

    }
);


/* ========================================
   FAVORITE
======================================== */

function toggleFavorite(
    index,
    star
){

    let fav =
        JSON.parse(
            localStorage.getItem(
                "mehedi_tv_favorites"
            ) || "[]"
        );


    if(
        fav.includes(index)
    ){

        fav =
            fav.filter(
                function(x){

                    return x !== index;

                }
            );

    }

    else{

        fav.push(index);

    }


    localStorage.setItem(
        "mehedi_tv_favorites",
        JSON.stringify(fav)
    );


    updateStar(
        index,
        star
    );

}


function updateStar(
    index,
    star
){

    let fav =
        JSON.parse(
            localStorage.getItem(
                "mehedi_tv_favorites"
            ) || "[]"
        );


    if(
        fav.includes(index)
    ){

        star.innerText =
            "★";

        star.classList.add(
            "active"
        );

    }

    else{

        star.innerText =
            "☆";

        star.classList.remove(
            "active"
        );

    }

}


